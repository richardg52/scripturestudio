// Table of 7 Family Feud rules, proven (node table-of-7-backend/tests/feud_rules_test.mjs).
import { feudNorm, feudBoard, feudSecret, feudInit, feudApply, FEUD_PROMPTS } from "../supabase/functions/games/feud.js";
let fails = 0;
const check = (name, ok, detail = "") => { if(!ok) fails++; console.log((ok ? "PASS " : "FAIL ") + name + (ok ? "" : `  -> ${JSON.stringify(detail)}`)); };
const throws = f => { try { f(); return false; } catch { return true; } };

check("spellings group together", new Set(["Pizza", "pizzas", "the pizza!", "  PIZZA "].map(feudNorm)).size === 1);
check("different words stay apart", feudNorm("soda") !== feudNorm("pop"));
check("plurals group: cookies/Cookie, berries/berry, turkeys/turkey, movies/movie", feudNorm("cookies") === feudNorm("Cookie") && feudNorm("berries") === feudNorm("berry") && feudNorm("turkeys") === feudNorm("turkey") && feudNorm("movies") === feudNorm("Movie"));
check("cookies is not turned into another word", feudNorm("cookies") === "cookie", feudNorm("cookies"));
const b = feudBoard(["Pizza", "pizza", "Wings", "pizzas", "wings", "Salad", "", "  ", "Tacos", "Fish", "Rice", "Greens", "Ribs"]);
check("points are the number of people who said it, most first", b[0].t === "pizza" || b[0].t === "Pizza", b);
check("pizza counted 3 times (Pizza, pizza, pizzas: the real count)", b[0].n === 3, b);
check("wings counted 2 times", b[1].n === 2 && /wings/i.test(b[1].t), b);
check("blank answers are not counted", b.reduce((s, x) => s + x.n, 0) <= 11, b);
check("at most six answers on the board", b.length === 6, b);
check("every count on the board adds up to no more than the people asked", feudBoard(["a1", "a1", "b2"]).reduce((s, x) => s + x.n, 0) === 3);

const sec = feudSecret(["Q1", "Q2", "Q3"], [{ answers: ["Pizza", "", "Red"] }, { answers: ["pizza", "", "Blue"] }, { answers: ["Wings", "", "red"] }]);
check("a question nobody answered is skipped", JSON.stringify(sec.order) === "[0,2]", sec.order);
let st = feudInit(sec, "s1", 3);
check("the board starts hidden", st.shown.every(x => x === null) && st.slots === 2 && st.prompt === "Q1" && st.turn === 0, st);
check("no answer text reaches the phone before it's revealed", !JSON.stringify(st).includes("izza") && !JSON.stringify(st).includes("Wings"), st);
let r = feudApply(st, sec, { reveal: 0 }); st = r.st;
check("a reveal shows the answer and banks its points", st.shown[0].n === 2 && st.bank === 2 && st.last.kind === "hit", st);
check("the same answer can't be revealed twice", throws(() => feudApply(st, sec, { reveal: 0 })));
check("a slot that isn't on the board is refused", throws(() => feudApply(st, sec, { reveal: 5 })));
r = feudApply(st, sec, { strike: true }); st = r.st; r = feudApply(st, sec, { strike: true }); st = r.st;
check("two strikes, still the same team", st.strikes === 2 && st.turn === 0 && st.phase === "play", st);
r = feudApply(st, sec, { strike: true }); st = r.st;
check("three strikes hand the other team one guess to steal", st.phase === "steal" && st.turn === 1, st);
const steal = feudApply(st, sec, { reveal: 1 });
check("a good steal takes the whole bank", steal.st.score[1] === 3 && steal.st.score[0] === 0 && steal.st.phase === "between", steal.st);
r = feudApply(st, sec, { strike: true }); st = r.st;
check("a missed steal gives the bank to the first team", st.score[0] === 2 && st.score[1] === 0 && st.phase === "between", st);
check("the rest of the board shows at the end of the round", st.shown.every(Boolean), st);
check("between rounds only Next round is allowed", throws(() => feudApply(st, sec, { reveal: 1 })));
r = feudApply(st, sec, { next: true }); st = r.st;
check("round 2: the other team starts, the board is fresh", st.round === 2 && st.turn === 1 && st.prompt === "Q3" && st.bank === 0 && st.strikes === 0 && st.shown.every(x => x === null), st);
r = feudApply(st, sec, { reveal: 0 }); st = r.st; r = feudApply(st, sec, { reveal: 1 });
check("clearing the board wins the round, and the last round ends the game", r.over && r.st.score[1] === 3 && r.over.winner === 1 && r.over.why === "2–3", r);
check("a made-up move is refused", throws(() => feudApply(feudInit(sec, "s1", 3), sec, { win: true })));
check("thirty questions in the bank, none repeated", FEUD_PROMPTS.length === 30 && new Set(FEUD_PROMPTS).size === 30);
import { readFileSync } from "node:fs";
const app = readFileSync(new URL("../../table-of-7/index.html", import.meta.url), "utf8"), srv = readFileSync(new URL("../supabase/functions/games/feud.js", import.meta.url), "utf8");
const appList = (app.match(/\/\* FEUD PROMPTS START[^\n]*\n([\s\S]*?)\/\* FEUD PROMPTS END \*\//) || [])[1], srvList = (srv.match(/export (const FEUD_PROMPTS = \[[\s\S]*?\n\];\n)/) || [])[1];
check("the app's copy of the questions matches the server's", !!appList && appList === srvList, { app: (appList || "").slice(0, 60) });
console.log(fails ? `\n${fails} FAILED` : "\nALL PROOFS HOLD");
process.exit(fails ? 1 : 0);
